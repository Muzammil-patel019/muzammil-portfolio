"""Package only reviewed starter sources; never include a local venv or test artifacts."""
from pathlib import Path
import io
import zipfile
import base64

root = Path(__file__).resolve().parents[1]
source = root / "automation-lab-starter"
files = [
    ".gitignore", "README.md", "requirements.txt", "pytest.ini",
    "tests/api/test_catalogue.py", "tests/ui/test_storefront.py",
]
buffer = io.BytesIO()
with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
    for relative in sorted(files):
        entry = zipfile.ZipInfo("automation-lab-starter/" + relative, (2026, 1, 1, 0, 0, 0))
        entry.compress_type = zipfile.ZIP_DEFLATED
        archive.writestr(entry, (source / relative).read_bytes())
encoded = base64.b64encode(buffer.getvalue()).decode()
(root / "web/lib/lab/starter.ts").write_text(
    '// Generated by scripts/package-lab-starter.py\nexport const starterZip = "' + encoded + '";\n'
)

framework = root / "automation-lab-framework"
packed = io.BytesIO()
with zipfile.ZipFile(packed, "w", zipfile.ZIP_DEFLATED) as archive:
    for path in sorted(framework.rglob("*")):
        relative = path.relative_to(framework)
        if not path.is_file() or any(part in {".venv", "artifacts", "__pycache__", ".pytest_cache"} for part in relative.parts):
            continue
        if path.suffix not in {".py", ".md", ".txt", ".ini"} and path.name != ".gitignore":
            continue
        entry = zipfile.ZipInfo("automation-lab-framework/" + str(relative), (2026, 1, 1, 0, 0, 0))
        entry.compress_type = zipfile.ZIP_DEFLATED
        archive.writestr(entry, path.read_bytes())
(root / "web/lib/lab/framework.ts").write_text('// Generated by scripts/package-lab-starter.py\nexport const frameworkZip = "' + base64.b64encode(packed.getvalue()).decode() + '";\n')
